import puppeteer from "puppeteer-core";
import os from "node:os";
import { join, dirname } from "node:path";
import { readdirSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
const here = join(dirname(fileURLToPath(import.meta.url)), "..");
const root = join(os.homedir(), ".cache/puppeteer/chrome-headless-shell");
const v = readdirSync(root).sort().pop();
const b = await puppeteer.launch({ executablePath: join(root, v, "chrome-headless-shell-win64/chrome-headless-shell.exe"), args: ["--allow-file-access-from-files"] });
const p = await b.newPage();
await p.setViewport({ width: 1920, height: 1080 });
p.on("pageerror", (e) => console.log("pageerror:", e.message));
console.log("goto"); await p.goto(pathToFileURL(join(here, "index.html")).href, { waitUntil: "load" });
console.log("loaded");
const n = await p.evaluate(() => [document.querySelectorAll("#world *").length, typeof window.__timelines.main]);
console.log(n);
await p.screenshot({ path: join(here, "snapshots/probe.png") }); console.log("shot0");
await p.evaluate(() => { for (const f of D.frameFns) f(1); }); console.log("all fns ok");
await p.screenshot({ path: join(here, "snapshots/probe1.png") }); console.log("shot after fns");
await p.evaluate(() => { window.__timelines.main.seek(1, false); return 1; }); console.log("seek ok");
console.log("seeked");
await p.screenshot({ path: join(here, "snapshots/probe1.png") }); console.log("shot1");
await b.close();
