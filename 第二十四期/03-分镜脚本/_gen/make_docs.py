# 有拍点表时，画面跟着音乐真实的拍点走：MiniMax 不严格守拍，硬拉音乐会出声音问题，所以反过来让 B(n) 查表。
# 拍点表由 04-声音/music/beats.py --json 生成，放在工程 assets/audio/beatmap.json（第一拍已对齐到 0 秒）。
import json
_BM = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "videos", "hok-split", "assets", "audio", "beatmap.json"))
