PUNCT = set("，。、：；？！“”「」《》（）()·…—,.:;?! ")

def B(n):
    if not BT: return n * BEAT
    i = int(n)
    if i + 1 < len(BT): return BT[i] + (BT[i + 1] - BT[i]) * (n - i)
    return BT[-1] + (n - len(BT) + 1) * (BT[-1] - BT[-9]) / 8
def ts(n): return f"{B(n):.1f}"
def plain(s): return s.replace("<hi>", "").replace("</hi>", "")
def nchar(s): return len([c for c in plain(s) if c not in PUNCT])
def beats_for(s): return math.ceil(max(MIN_S, nchar(s) / RATE) / BEAT)

