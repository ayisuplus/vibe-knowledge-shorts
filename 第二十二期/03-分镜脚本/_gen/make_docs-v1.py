LINE_MAX = 26
def wrap(s):
    p = plain(s)
    if nchar(p) <= LINE_MAX: return s
    mid = len(p) / 2
    cands = [i + 1 for i, ch in enumerate(p) if ch in "，：；、？。" and 0 < i + 1 < len(p)]
    cands = [c for c in cands if max(c, len(p) - c) <= 32] or [round(mid)]
    cut = min(cands, key=lambda c: abs(c - mid))
    # 把切点映射回带 <hi> 标记的原文
    k = seen = 0
    while seen < cut:
        if s.startswith("<hi>", k): k += 4; continue
        if s.startswith("</hi>", k): k += 5; continue
        k += 1; seen += 1
    while s.startswith("</hi>", k): k += 5
    return s[:k] + "\n" + s[k:]
